# Labels keep their offsets (in points) from the marker lines; where the narrower
# axes would make neighbouring labels collide, they are pushed apart to the same
# minimum spacing the original figure has (~13.9 pt).
def _spread(c, gap=13.9):
    c = np.asarray(c, float)
    order = np.argsort(c)
    cs = c[order]
    for _ in range(500):
        moved = False
        for i in range(len(cs) - 1):
            d = cs[i + 1] - cs[i]
            if d < gap - 1e-9:
                m = (gap - d) / 2
                cs[i] -= m
                cs[i + 1] += m
                moved = True
        if not moved:
            break
    out = np.empty_like(cs)
    out[order] = cs
    return out

